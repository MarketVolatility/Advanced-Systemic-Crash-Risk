/** The build verifies every ID/tag against DashboardElements; missing nodes fail here. */
function requiredElement<K extends keyof DashboardElements>(id: K): DashboardElements[K] {
 const element = document.getElementById(id);
 if (!element) throw new Error(`Missing dashboard element: ${id}`);
 return element as DashboardElements[K];
}
